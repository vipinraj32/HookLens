"""Generate app/analyzers/permissions_generated.py from the pinned Uniswap v4-core sources.

Flags are parsed from v4-core `src/libraries/Hooks.sol`; callback selectors come from the
compiled `IHooks` artifact (`forge build` output, `methodIdentifiers`). Nothing is hardcoded:
if v4-core is bumped, re-run this script and the sync test will detect drift.

    python backend/scripts/gen_permissions.py
"""

from __future__ import annotations

import hashlib
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CORE = ROOT / "contracts" / "lib" / "v4-periphery" / "lib" / "v4-core"
HOOKS_SOL = CORE / "src" / "libraries" / "Hooks.sol"
IHOOKS_ARTIFACT = ROOT / "contracts" / "out" / "IHooks.sol" / "IHooks.json"
OUT = ROOT / "backend" / "app" / "analyzers" / "permissions_generated.py"

FLAG_RE = re.compile(r"uint160\s+internal\s+constant\s+([A-Z_]+)_FLAG\s*=\s*1\s*<<\s*(\d+)\s*;")
MASK_RE = re.compile(r"ALL_HOOK_MASK\s*=\s*uint160\(\(1\s*<<\s*(\d+)\)\s*-\s*1\)")

# Flag name -> IHooks callback function implementing it. Return-delta flags have no separate
# callback; they change how the return value of the base callback is interpreted.
CALLBACK_FOR_FLAG = {
    "BEFORE_INITIALIZE": "beforeInitialize",
    "AFTER_INITIALIZE": "afterInitialize",
    "BEFORE_ADD_LIQUIDITY": "beforeAddLiquidity",
    "AFTER_ADD_LIQUIDITY": "afterAddLiquidity",
    "BEFORE_REMOVE_LIQUIDITY": "beforeRemoveLiquidity",
    "AFTER_REMOVE_LIQUIDITY": "afterRemoveLiquidity",
    "BEFORE_SWAP": "beforeSwap",
    "AFTER_SWAP": "afterSwap",
    "BEFORE_DONATE": "beforeDonate",
    "AFTER_DONATE": "afterDonate",
    "BEFORE_SWAP_RETURNS_DELTA": "beforeSwap",
    "AFTER_SWAP_RETURNS_DELTA": "afterSwap",
    "AFTER_ADD_LIQUIDITY_RETURNS_DELTA": "afterAddLiquidity",
    "AFTER_REMOVE_LIQUIDITY_RETURNS_DELTA": "afterRemoveLiquidity",
}
# Hooks.Permissions struct field name for each flag.
STRUCT_FIELD = {
    "BEFORE_INITIALIZE": "beforeInitialize",
    "AFTER_INITIALIZE": "afterInitialize",
    "BEFORE_ADD_LIQUIDITY": "beforeAddLiquidity",
    "AFTER_ADD_LIQUIDITY": "afterAddLiquidity",
    "BEFORE_REMOVE_LIQUIDITY": "beforeRemoveLiquidity",
    "AFTER_REMOVE_LIQUIDITY": "afterRemoveLiquidity",
    "BEFORE_SWAP": "beforeSwap",
    "AFTER_SWAP": "afterSwap",
    "BEFORE_DONATE": "beforeDonate",
    "AFTER_DONATE": "afterDonate",
    "BEFORE_SWAP_RETURNS_DELTA": "beforeSwapReturnDelta",
    "AFTER_SWAP_RETURNS_DELTA": "afterSwapReturnDelta",
    "AFTER_ADD_LIQUIDITY_RETURNS_DELTA": "afterAddLiquidityReturnDelta",
    "AFTER_REMOVE_LIQUIDITY_RETURNS_DELTA": "afterRemoveLiquidityReturnDelta",
}


def _git_commit(path: Path) -> str:
    try:
        return subprocess.check_output(["git", "-C", str(path), "rev-parse", "HEAD"], text=True).strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def render() -> str:
    text = HOOKS_SOL.read_text(encoding="utf-8")
    flags = [(name, int(bit)) for name, bit in FLAG_RE.findall(text)]
    mask_bits = MASK_RE.search(text)
    if not flags or not mask_bits:
        raise SystemExit("could not parse Hooks.sol flags")
    unknown = {n for n, _ in flags} - set(CALLBACK_FOR_FLAG)
    if unknown:
        raise SystemExit(f"Hooks.sol defines flags unknown to the generator: {sorted(unknown)}")
    if not IHOOKS_ARTIFACT.exists():
        raise SystemExit("IHooks artifact missing: run `forge build` in contracts/ first")
    methods: dict[str, str] = json.loads(IHOOKS_ARTIFACT.read_text(encoding="utf-8"))["methodIdentifiers"]
    by_name = {sig.split("(")[0]: (sig, "0x" + sel) for sig, sel in methods.items()}
    sha = hashlib.sha256(text.encode()).hexdigest()
    lines = [
        '"""GENERATED by backend/scripts/gen_permissions.py. Do not edit by hand.',
        "",
        "Source: Uniswap v4-core src/libraries/Hooks.sol and the compiled IHooks interface.",
        '"""',
        "",
        f"V4_CORE_COMMIT = {_git_commit(CORE)!r}",
        f"HOOKS_SOL_SHA256 = {sha!r}",
        f"ALL_HOOK_MASK = (1 << {mask_bits.group(1)}) - 1",
        "",
        "# (flag name, bit, Hooks.Permissions field, callback name, callback signature, selector)",
        "FLAGS: tuple[tuple[str, int, str, str, str, str], ...] = (",
    ]
    for name, bit in sorted(flags, key=lambda x: -x[1]):
        cb = CALLBACK_FOR_FLAG[name]
        sig, sel = by_name[cb]
        lines.append(f"    ({name!r}, {bit}, {STRUCT_FIELD[name]!r}, {cb!r}, {sig!r}, {sel!r}),")
    lines += [")", "", "CALLBACK_SELECTORS: dict[str, str] = {"]
    for cb in sorted(set(CALLBACK_FOR_FLAG.values())):
        lines.append(f"    {cb!r}: {by_name[cb][1]!r},")
    lines += ["}", ""]
    return "\n".join(lines)


def main() -> int:
    content = render()
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != content:
            print("permissions_generated.py is out of date; run backend/scripts/gen_permissions.py")
            return 1
        return 0
    OUT.write_text(content, encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
