"use client";

import { Sparkles } from "lucide-react";
import Link from "next/link";

import { useEvidenceByIds, useExplanations, useRequestExplanation } from "@/lib/api/hooks";
import type { Explanation, Finding } from "@/lib/api/models";
import { formatDate, humanize } from "@/lib/format";

import { EvidenceCard } from "./evidence";
import { Badge, Button, ErrorState, Notice, SeverityBadge, Spinner, StatusBadge, TagBadge } from "./ui";

interface TechContent {
  summary: string;
  mechanism: string;
  evidence_refs: string[];
  source_refs: { file: string; line_start: number; line_end: number }[];
  simulation_refs: { scenario: string; step: string }[];
}
interface LpContent {
  what_it_means: string;
  when_it_matters: string;
  what_to_check: string[];
  evidence_refs: string[];
}

function ExplanationView({ e }: { e: Explanation }) {
  const content = e.content as { technical?: TechContent | null; lp?: LpContent | null } | null | undefined;
  const validation = (e.validation ?? {}) as { reason?: string; errors?: string[]; ok?: boolean };
  if (e.status === "unavailable") {
    return <Notice>{validation.reason ?? "AI explanations are not available on this server."}</Notice>;
  }
  if (e.status === "queued" || e.status === "running") return <Spinner label="Generating and validating explanation…" />;
  if (e.status === "rejected" || e.status === "failed") {
    return (
      <Notice tone="warn">
        <p className="font-medium">The explanation was {e.status} and is not shown.</p>
        {validation.errors?.length ? (
          <ul className="mt-2 list-disc pl-5 text-xs text-muted">
            {validation.errors.slice(0, 8).map((x, i) => (
              <li key={i}>{x}</li>
            ))}
          </ul>
        ) : validation.reason ? (
          <p className="mt-1 text-xs text-muted">{validation.reason}</p>
        ) : null}
      </Notice>
    );
  }
  const t = content?.technical;
  const lp = content?.lp;
  return (
    <div className="flex flex-col gap-4 text-sm">
      <p className="text-xs text-faint">
        Generated by {e.model ?? "model"} · {formatDate(e.created_at)} · passed the evidence validator. Severity is
        set by the deterministic rules, not by the model.
      </p>
      {t ? (
        <section>
          <h4 className="text-xs font-semibold uppercase tracking-wide text-faint">Technical</h4>
          <p className="mt-1.5 text-fg">{t.summary}</p>
          <p className="mt-2 whitespace-pre-line text-muted">{t.mechanism}</p>
          {t.source_refs.length ? (
            <p className="mt-2 font-mono text-xs text-faint">
              {t.source_refs.map((r) => `${r.file}:${r.line_start}-${r.line_end}`).join(" · ")}
            </p>
          ) : null}
        </section>
      ) : null}
      {lp ? (
        <section>
          <h4 className="text-xs font-semibold uppercase tracking-wide text-faint">For liquidity providers</h4>
          <p className="mt-1.5 text-fg">{lp.what_it_means}</p>
          <p className="mt-2 text-muted">{lp.when_it_matters}</p>
          {lp.what_to_check.length ? (
            <ul className="mt-2 list-disc pl-5 text-muted">
              {lp.what_to_check.map((x, i) => (
                <li key={i}>{x}</li>
              ))}
            </ul>
          ) : null}
        </section>
      ) : null}
    </div>
  );
}

function Explanations({ f }: { f: Finding }) {
  const list = useExplanations(f.scan_id, f.finding_id);
  const req = useRequestExplanation(f.scan_id, f.finding_id);
  const latest = list.data?.[0];
  const busy = latest && (latest.status === "queued" || latest.status === "running");
  return (
    <section className="flex flex-col gap-3 rounded-lg border border-line p-4">
      <div className="flex flex-wrap items-center justify-between gap-2">
        <h3 className="flex items-center gap-2 text-sm font-semibold">
          <Sparkles aria-hidden="true" className="size-4 text-accent" /> Explanation
        </h3>
        <Button size="sm" onClick={() => req.mutate()} loading={req.isPending} disabled={!!busy}>
          {latest ? "Regenerate" : "Explain this finding"}
        </Button>
      </div>
      {req.isError ? <ErrorState error={req.error} title="Request failed" /> : null}
      {list.isError ? <ErrorState error={list.error} onRetry={() => list.refetch()} /> : null}
      {latest ? (
        <ExplanationView e={latest} />
      ) : list.isPending ? null : (
        <p className="text-sm text-muted">
          Optional. Uses only this finding&apos;s evidence; the output is checked by a validator before display.
        </p>
      )}
    </section>
  );
}

export function FindingDetail({ f }: { f: Finding }) {
  const ev = useEvidenceByIds(f.scan_id, f.evidence_ids);
  return (
    <div className="flex flex-col gap-5">
      <header className="flex flex-col gap-2">
        <div className="flex flex-wrap items-center gap-2">
          <SeverityBadge severity={f.severity} />
          <StatusBadge status={f.status} />
          <TagBadge tag={f.confidence_basis} title="Confidence basis" />
          <Badge className="text-muted">{humanize(f.category)}</Badge>
        </div>
        <h2 className="text-lg font-semibold leading-snug">{f.title}</h2>
        <p className="font-mono text-xs text-faint">
          {f.finding_id} · {f.analyzer_id}/{f.rule_id}
        </p>
      </header>

      <p className="text-sm text-fg/90">{f.description}</p>

      <dl className="grid gap-4 text-sm">
        <div>
          <dt className="text-xs uppercase tracking-wide text-faint">Why this severity</dt>
          <dd className="mt-1 text-muted">{f.severity_rationale}</dd>
        </div>
        <div>
          <dt className="text-xs uppercase tracking-wide text-faint">LP implication</dt>
          <dd className="mt-1 text-muted">{f.lp_implications}</dd>
        </div>
        <div>
          <dt className="text-xs uppercase tracking-wide text-faint">Remediation</dt>
          <dd className="mt-1 text-muted">{f.remediation}</dd>
        </div>
        {f.affected_functions.length ? (
          <div>
            <dt className="text-xs uppercase tracking-wide text-faint">Affected functions</dt>
            <dd className="mt-1 flex flex-wrap gap-1">
              {f.affected_functions.map((x) => (
                <Badge key={x} className="font-mono text-muted">
                  {x}
                </Badge>
              ))}
            </dd>
          </div>
        ) : null}
        {f.related_scenarios.length ? (
          <div>
            <dt className="text-xs uppercase tracking-wide text-faint">Related scenarios</dt>
            <dd className="mt-1 flex flex-wrap gap-1">
              {f.related_scenarios.map((x) => (
                <Link key={x} href={`/app/scans/${f.scan_id}/lab`} className="rounded-md border border-line px-1.5 py-0.5 text-xs text-accent hover:bg-surface-2">
                  {humanize(x)}
                </Link>
              ))}
            </dd>
          </div>
        ) : null}
        {f.limitations.length ? (
          <div>
            <dt className="text-xs uppercase tracking-wide text-faint">Limitations</dt>
            <dd className="mt-1">
              <ul className="list-disc pl-5 text-muted">
                {f.limitations.map((x, i) => (
                  <li key={i}>{x}</li>
                ))}
              </ul>
            </dd>
          </div>
        ) : null}
      </dl>

      <section className="flex flex-col gap-3">
        <h3 className="text-sm font-semibold">Evidence ({f.evidence_ids.length})</h3>
        {ev.isPending && f.evidence_ids.length ? <Spinner label="Loading evidence…" /> : null}
        {ev.isError ? <ErrorState error={ev.error} onRetry={() => ev.refetch()} /> : null}
        {ev.data?.items.map((e) => <EvidenceCard key={e.evidence_id} ev={e} compact />)}
      </section>

      <Explanations f={f} />
    </div>
  );
}
